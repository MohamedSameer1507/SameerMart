package com.sameer.sameermart.dao;

import com.sameer.sameermart.config.DatabaseConfig;
import com.sameer.sameermart.model.Product;
import com.sameer.sameermart.model.User;
import com.sameer.sameermart.model.WishlistItem;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class WishlistDAOTest {

    private static UserDAO userDAO;
    private static ProductDAO productDAO;
    private static WishlistDAO wishlistDAO;
    private static User seller;
    private static User buyer;

    @BeforeAll
    public static void setUp() throws Exception {
        userDAO = new UserDAO();
        productDAO = new ProductDAO();
        wishlistDAO = new WishlistDAO();

        try (Connection conn = DatabaseConfig.getDataSource().getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS users (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL,
                        email VARCHAR(150) NOT NULL UNIQUE,
                        password VARCHAR(255) NOT NULL,
                        role VARCHAR(30) NOT NULL
                    );
                    CREATE TABLE IF NOT EXISTS products (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        seller_id INT NOT NULL,
                        name VARCHAR(150) NOT NULL,
                        description VARCHAR(1000),
                        category VARCHAR(100) NOT NULL,
                        price DECIMAL(12,2) NOT NULL,
                        quantity INT NOT NULL,
                        image_url VARCHAR(255) DEFAULT 'default-product.svg',
                        active BOOLEAN NOT NULL DEFAULT TRUE,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        CONSTRAINT fk_products_seller_w FOREIGN KEY (seller_id) REFERENCES users(id)
                    );
                    CREATE TABLE IF NOT EXISTS wishlist (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        buyer_id INT NOT NULL,
                        product_id INT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        CONSTRAINT fk_wishlist_buyer_w FOREIGN KEY (buyer_id) REFERENCES users(id) ON DELETE CASCADE,
                        CONSTRAINT fk_wishlist_product_w FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
                        CONSTRAINT uq_wishlist_buyer_product_w UNIQUE (buyer_id, product_id)
                    );
                    """);
        }

        String suffix = UUID.randomUUID().toString().substring(0, 8);
        seller = new User("WishlistSeller_" + suffix, "w_seller_" + suffix + "@test.com", "pass123", "SELLER");
        userDAO.registerUser(seller);
        seller = userDAO.findByEmail(seller.getEmail());

        buyer = new User("WishlistBuyer_" + suffix, "w_buyer_" + suffix + "@test.com", "pass123", "BUYER");
        userDAO.registerUser(buyer);
        buyer = userDAO.findByEmail(buyer.getEmail());
    }

    private Product createTestProduct(String name, int qty) {
        Product p = new Product(seller.getId(), name, "Description", "Category", new BigDecimal("199.99"), qty, "item.jpg");
        productDAO.addProduct(p);
        List<Product> products = productDAO.findBySellerId(seller.getId());
        return products.stream().filter(prod -> prod.getName().equals(name)).findFirst().orElseThrow();
    }

    @Test
    public void testAddToWishlistAndCheckStatus() {
        String prodName = "WishlistProduct_" + UUID.randomUUID().toString().substring(0, 8);
        Product product = createTestProduct(prodName, 10);

        assertFalse(wishlistDAO.isProductInWishlist(buyer.getId(), product.getId()), "Should not be wishlisted initially");

        boolean added = wishlistDAO.addToWishlist(buyer.getId(), product.getId());
        assertTrue(added, "addToWishlist should return true");
        assertTrue(wishlistDAO.isProductInWishlist(buyer.getId(), product.getId()), "Should be wishlisted after add");
    }

    @Test
    public void testAddToWishlistIdempotent() {
        String prodName = "WishlistProductDup_" + UUID.randomUUID().toString().substring(0, 8);
        Product product = createTestProduct(prodName, 5);

        assertTrue(wishlistDAO.addToWishlist(buyer.getId(), product.getId()));
        // Duplicate add should succeed cleanly without crashing
        assertTrue(wishlistDAO.addToWishlist(buyer.getId(), product.getId()), "Duplicate add should return true");
    }

    @Test
    public void testGetWishlistByBuyerId() {
        String prodName = "WishlistDetails_" + UUID.randomUUID().toString().substring(0, 8);
        Product product = createTestProduct(prodName, 15);
        wishlistDAO.addToWishlist(buyer.getId(), product.getId());

        List<WishlistItem> items = wishlistDAO.getWishlistByBuyerId(buyer.getId());
        assertFalse(items.isEmpty(), "Wishlist should contain items");

        WishlistItem match = items.stream().filter(it -> it.getProductId() == product.getId()).findFirst().orElse(null);
        assertTrue(match != null, "Item should match added product");
        assertEquals(prodName, match.getProductName());
        assertEquals(new BigDecimal("199.99"), match.getProductPrice());
        assertTrue(match.isInStock());
    }

    @Test
    public void testRemoveFromWishlist() {
        String prodName = "WishlistRemove_" + UUID.randomUUID().toString().substring(0, 8);
        Product product = createTestProduct(prodName, 8);
        wishlistDAO.addToWishlist(buyer.getId(), product.getId());
        assertTrue(wishlistDAO.isProductInWishlist(buyer.getId(), product.getId()));

        boolean removed = wishlistDAO.removeFromWishlist(buyer.getId(), product.getId());
        assertTrue(removed, "removeFromWishlist should return true");
        assertFalse(wishlistDAO.isProductInWishlist(buyer.getId(), product.getId()), "Should no longer be in wishlist");
    }

    @Test
    public void testGetWishlistCount() {
        String suffix = UUID.randomUUID().toString().substring(0, 8);
        User freshBuyer = new User("FreshBuyer_" + suffix, "fresh_" + suffix + "@test.com", "pass123", "BUYER");
        userDAO.registerUser(freshBuyer);
        freshBuyer = userDAO.findByEmail(freshBuyer.getEmail());

        assertEquals(0, wishlistDAO.getWishlistCount(freshBuyer.getId()));

        Product p1 = createTestProduct("CountP1_" + suffix, 10);
        Product p2 = createTestProduct("CountP2_" + suffix, 20);

        wishlistDAO.addToWishlist(freshBuyer.getId(), p1.getId());
        assertEquals(1, wishlistDAO.getWishlistCount(freshBuyer.getId()));

        wishlistDAO.addToWishlist(freshBuyer.getId(), p2.getId());
        assertEquals(2, wishlistDAO.getWishlistCount(freshBuyer.getId()));
    }

    @Test
    public void testClearWishlist() {
        String suffix = UUID.randomUUID().toString().substring(0, 8);
        User clearBuyer = new User("ClearBuyer_" + suffix, "clear_" + suffix + "@test.com", "pass123", "BUYER");
        userDAO.registerUser(clearBuyer);
        clearBuyer = userDAO.findByEmail(clearBuyer.getEmail());

        Product p1 = createTestProduct("ClearP1_" + suffix, 10);
        wishlistDAO.addToWishlist(clearBuyer.getId(), p1.getId());
        assertEquals(1, wishlistDAO.getWishlistCount(clearBuyer.getId()));

        wishlistDAO.clearWishlist(clearBuyer.getId());
        assertEquals(0, wishlistDAO.getWishlistCount(clearBuyer.getId()));
    }
}
