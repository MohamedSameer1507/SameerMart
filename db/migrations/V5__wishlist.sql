-- V5__wishlist.sql
-- Wishlist feature (Option O1 per Anna University Capstone Spec)
-- Allows buyers to save products for later and move them to cart

CREATE TABLE IF NOT EXISTS wishlist (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id INT NOT NULL,
    product_id INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wishlist_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_product
        FOREIGN KEY (product_id)
        REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT uq_wishlist_buyer_product
        UNIQUE (buyer_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_wishlist_buyer_id ON wishlist(buyer_id);
CREATE INDEX IF NOT EXISTS idx_wishlist_product_id ON wishlist(product_id);
